"""
M17 — the stored event is one immutable fact, not two nullable columns.

m16 proved the failure mode against the live receiver: a re-verification wrote `event_id = NULL`
over a stored claim while its body survived, so the next delivery minted a fresh body under the
same `event_id` and RESOLVE correctly answered 409 "already recorded for a different payload".
These tests hold the contract that closes that door:

- `mark_confirmed` preserves a stored event id unless a replacement is named;
- the (event_id, event_body) pair is immutable once any part of it exists;
- a half-persisted pair fails closed — nothing rebuilt, nothing sent, nothing rewritten.

The redelivery tests assert byte identity on the wire and survival of the pair in storage, because
"same status" is exactly the assertion that failed to notice the defect: the regenerated bytes and
the correct ones both produce a refusal from the receiver, but only the correct ones match what the
receiver recorded the first time.
"""
from __future__ import annotations

import pytest
from conftest import handoff
from merchant_channel.outbox import (
    CONFIRMED,
    EventRecordConflict,
    LINKAGE_DELIVERY_UNKNOWN,
    Outbox,
)

EVENT_ID = "evt-000000000000000000000001"
EVENT_BODY = (
    '{"event_id":"evt-000000000000000000000001",'
    '"issued_at":"2026-11-02T09:15:31.257107+00:00"}'
)
MERCHANT_ORDER_GID = "gid://shopify/Order/9000000000000001"


# --------------------------------------------------------------------------- mark_confirmed
def test_mark_confirmed_preserves_a_stored_event_id_when_none_is_supplied(outbox: Outbox):
    """
    Re-verification confirms the order, not the claim: it has nothing to say about the event id.

    The m16 defect lived exactly here — a mark_confirmed that defaulted the id to NULL and wrote
    it, severing the row's event_id from the body it belongs to.
    """
    correlation = "RESOLVE-order_p-000000000000"
    outbox.reserve(correlation_id=correlation, resolve_order_id="order_p", payload_hash="8" * 16)
    outbox.record_event(correlation, event_id=EVENT_ID, event_body=EVENT_BODY)

    outbox.mark_confirmed(correlation, MERCHANT_ORDER_GID)

    record = outbox.get(correlation)
    assert record.status == CONFIRMED
    assert record.event_id == EVENT_ID
    assert record.event_body == EVENT_BODY


def test_mark_confirmed_still_honours_an_explicitly_supplied_event_id(outbox: Outbox):
    correlation = "RESOLVE-order_q-000000000000"
    outbox.reserve(correlation_id=correlation, resolve_order_id="order_q", payload_hash="9" * 16)
    outbox.mark_confirmed(correlation, MERCHANT_ORDER_GID, event_id=EVENT_ID)
    assert outbox.get(correlation).event_id == EVENT_ID


# --------------------------------------------------------------------------- the pair is immutable
def test_record_event_accepts_an_identical_redelivery_as_a_no_op(outbox: Outbox):
    correlation = "RESOLVE-order_r-000000000000"
    outbox.reserve(correlation_id=correlation, resolve_order_id="order_r", payload_hash="a" * 16)
    outbox.record_event(correlation, event_id=EVENT_ID, event_body=EVENT_BODY)
    outbox.record_event(correlation, event_id=EVENT_ID, event_body=EVENT_BODY)
    record = outbox.get(correlation)
    assert record.event_id == EVENT_ID
    assert record.event_body == EVENT_BODY


def test_record_event_refuses_different_bytes_under_the_stored_id(outbox: Outbox):
    """A fresh body under a stored id is the same-id/different-payload mismatch the receiver refuses."""
    correlation = "RESOLVE-order_s-000000000000"
    outbox.reserve(correlation_id=correlation, resolve_order_id="order_s", payload_hash="b" * 16)
    outbox.record_event(correlation, event_id=EVENT_ID, event_body=EVENT_BODY)

    with pytest.raises(EventRecordConflict):
        outbox.record_event(
            correlation,
            event_id=EVENT_ID,
            event_body='{"event_id":"evt-000000000000000000000001","issued_at":"later"}',
        )

    assert outbox.get(correlation).event_body == EVENT_BODY


def test_record_event_refuses_a_different_event_id_over_a_stored_pair(outbox: Outbox):
    correlation = "RESOLVE-order_t-000000000000"
    outbox.reserve(correlation_id=correlation, resolve_order_id="order_t", payload_hash="c" * 16)
    outbox.record_event(correlation, event_id=EVENT_ID, event_body=EVENT_BODY)

    with pytest.raises(EventRecordConflict):
        outbox.record_event(correlation, event_id="evt-other", event_body=EVENT_BODY)

    assert outbox.get(correlation).event_id == EVENT_ID


def test_record_event_refuses_to_complete_a_half_persisted_pair(outbox: Outbox):
    """
    A body whose id is gone cannot be completed from outside: an event id is derived from the
    pairing, not from the body, so no caller can prove a candidate id belongs to those bytes.
    """
    correlation = "RESOLVE-order_u-000000000000"
    outbox.reserve(correlation_id=correlation, resolve_order_id="order_u", payload_hash="d" * 16)
    outbox.record_event(correlation, event_id=EVENT_ID, event_body=EVENT_BODY)
    with outbox._connect() as conn:
        conn.execute(
            "UPDATE purchase_outbox SET event_id = NULL WHERE correlation_id = ?", (correlation,)
        )

    with pytest.raises(EventRecordConflict):
        outbox.record_event(correlation, event_id=EVENT_ID, event_body=EVENT_BODY)

    record = outbox.get(correlation)
    assert record.event_id is None
    assert record.event_body == EVENT_BODY


# --------------------------------------------------------------------------- redelivery is byte-identical
async def test_a_redelivery_after_a_lost_answer_resends_the_exact_stored_bytes(
    channel, store, resolve, outbox
):
    """
    The m16 sequence: deliver, RESOLVE cannot answer, re-verify, deliver again.

    Every re-verification runs through mark_confirmed — the exact write that used to null the
    stored event_id. After the fix the redelivery is the stored bytes on the wire and the stored
    pair in the row, RESOLVE's settled replay answer comes back for it, and Shopify is asked for
    no second order.
    """
    resolve.status_code = 503
    resolve.payload = {"detail": "the store could not confirm that order"}
    first = await channel.fulfil(handoff())
    assert first.status == "DELIVERY_UNKNOWN"
    stored = outbox.get(first.correlation_id)
    assert stored.event_id == first.event_id
    assert stored.event_body

    resolve.status_code = 200
    resolve.payload = {"outcome": "rejected", "already_processed": True}
    second = await channel.fulfil(handoff())

    assert second.status == "REFUSED_LINKAGE"
    assert second.event_id == first.event_id
    assert resolve.bodies[0] == resolve.bodies[1], "a retry must be the stored bytes, not a re-stamp"
    after = outbox.get(first.correlation_id)
    assert after.event_id == stored.event_id
    assert after.event_body == stored.event_body
    assert len(store.create_calls) == 1


async def test_a_pairing_completed_after_an_outage_carries_the_original_bytes(
    channel, store, resolve, outbox
):
    """The outage passes and the pairing completes: the accepted bytes are still the first bytes."""
    resolve.status_code = 503
    first = await channel.fulfil(handoff())
    assert first.status == "DELIVERY_UNKNOWN"

    resolve.status_code = 200
    resolve.payload = {"outcome": "linked"}
    second = await channel.fulfil(handoff())

    assert second.status == "CONFIRMED_LINKED"
    assert second.event_id == first.event_id
    assert resolve.bodies[0] == resolve.bodies[1]
    assert len(store.create_calls) == 1


# --------------------------------------------------------------------------- half-persisted fails closed
async def test_a_body_without_its_event_id_fails_closed_and_sends_nothing(
    channel, store, resolve, outbox
):
    """
    The m16 damage, reproduced exactly, then handed to the fixed channel.

    The row holds bytes whose id is gone. No honest delivery exists for that state: the body
    cannot be sent without an id, and minting a replacement under a rebuilt id is what produced
    the 409. So the channel refuses, sends nothing, and leaves the row for a human.
    """
    resolve.status_code = 503
    first = await channel.fulfil(handoff())
    assert first.status == "DELIVERY_UNKNOWN"
    stored_body = outbox.get(first.correlation_id).event_body
    with outbox._connect() as conn:
        conn.execute(
            "UPDATE purchase_outbox SET event_id = NULL WHERE correlation_id = ?",
            (first.correlation_id,),
        )

    resolve.status_code = 200
    resolve.payload = {"outcome": "linked"}
    second = await channel.fulfil(handoff())

    assert second.status == "REFUSED_LINKAGE"
    assert "half-persisted" in second.reason
    assert len(resolve.requests) == 1, "nothing may be sent for a half-persisted event"
    after = outbox.get(first.correlation_id)
    assert after.event_id is None
    assert after.event_body == stored_body
    assert after.linkage == LINKAGE_DELIVERY_UNKNOWN
    assert len(store.create_calls) == 1


async def test_an_event_id_without_its_body_fails_closed_and_sends_nothing(
    channel, store, resolve, outbox
):
    """The mirror damage: an id whose body is gone is a claim with nothing to send."""
    resolve.status_code = 503
    first = await channel.fulfil(handoff())
    assert first.status == "DELIVERY_UNKNOWN"
    stored_id = outbox.get(first.correlation_id).event_id
    with outbox._connect() as conn:
        conn.execute(
            "UPDATE purchase_outbox SET event_body = NULL WHERE correlation_id = ?",
            (first.correlation_id,),
        )

    resolve.status_code = 200
    resolve.payload = {"outcome": "linked"}
    second = await channel.fulfil(handoff())

    assert second.status == "REFUSED_LINKAGE"
    assert "half-persisted" in second.reason
    assert len(resolve.requests) == 1
    after = outbox.get(first.correlation_id)
    assert after.event_id == stored_id
    assert after.event_body is None
    assert after.linkage == LINKAGE_DELIVERY_UNKNOWN
    assert len(store.create_calls) == 1
